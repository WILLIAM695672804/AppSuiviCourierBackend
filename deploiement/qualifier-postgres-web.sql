-- Variante pour phpPgAdmin / pgAdmin : rend un TABLEAU au lieu de messages.
-- Les « RAISE NOTICE » du script principal ne s'affichent pas dans une
-- interface web. Ici, tout est temporaire : rien ne survit a la session.
-- Coller les trois instructions d'un coup.

CREATE TEMP TABLE zz_resultat (rang int, verdict text, test text, detail text);

DO $q$
DECLARE n int := 0; ext text; dispo bool;
BEGIN
    n := n + 1;
    INSERT INTO zz_resultat VALUES (n, 'INFO', 'Serveur', version());
    n := n + 1;
    INSERT INTO zz_resultat VALUES (n, 'INFO', 'Compte',
        format('%s sur %s, superutilisateur=%s', current_user, current_database(),
               (SELECT usesuper FROM pg_user WHERE usename = current_user)));

    n := n + 1;
    INSERT INTO zz_resultat VALUES (n,
        CASE WHEN current_setting('server_version_num')::int >= 160000
             THEN 'OK' ELSE 'BLOQUANT' END,
        'Version >= 16', current_setting('server_version'));

    FOREACH ext IN ARRAY ARRAY['pgcrypto','btree_gist','pg_trgm','unaccent'] LOOP
        SELECT EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = ext) INTO dispo;
        n := n + 1;
        INSERT INTO zz_resultat VALUES (n,
            CASE WHEN dispo THEN 'OK' ELSE 'BLOQUANT' END,
            'Extension ' || ext,
            CASE WHEN EXISTS (SELECT 1 FROM pg_extension WHERE extname = ext)
                 THEN 'deja installee'
                 WHEN dispo THEN 'installable'
                 ELSE 'ABSENTE du serveur (paquet contrib manquant)' END);
    END LOOP;

    BEGIN
        CREATE TEMP TABLE zz_p (le date NOT NULL) PARTITION BY RANGE (le);
        CREATE TEMP TABLE zz_p26 PARTITION OF zz_p FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'OK','Partitionnement declaratif','3 tables du socle');
    EXCEPTION WHEN OTHERS THEN
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'BLOQUANT','Partitionnement declaratif',SQLERRM);
    END;

    BEGIN
        CREATE TEMP TABLE zz_e (id bigint, p tstzrange, EXCLUDE USING gist (id WITH =, p WITH &&));
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'OK','EXCLUDE USING gist','sans equivalent ailleurs');
    EXCEPTION WHEN OTHERS THEN
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'BLOQUANT','EXCLUDE USING gist',SQLERRM);
    END;

    BEGIN
        CREATE TEMP TABLE zz_r (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            objet text,
            recherche tsvector GENERATED ALWAYS AS (to_tsvector('french', coalesce(objet,''))) STORED);
        CREATE INDEX ON zz_r USING GIN (recherche);
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'OK','TSVECTOR + GIN + « french »','18 colonnes du socle');
    EXCEPTION WHEN OTHERS THEN
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'BLOQUANT','TSVECTOR + GIN + « french »',SQLERRM);
    END;

    BEGIN
        CREATE TEMP TABLE zz_b (le timestamptz);
        CREATE INDEX ON zz_b USING BRIN (le);
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'OK','Index BRIN','journaux');
    EXCEPTION WHEN OTHERS THEN
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'BLOQUANT','Index BRIN',SQLERRM);
    END;

    BEGIN
        CREATE FUNCTION pg_temp.zz_d() RETURNS trigger LANGUAGE plpgsql AS $f$ BEGIN RETURN NEW; END $f$;
        CREATE TRIGGER zz BEFORE INSERT ON zz_b FOR EACH ROW EXECUTE FUNCTION pg_temp.zz_d();
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'OK','PL/pgSQL et declencheurs','14 fonctions, 11 declencheurs');
    EXCEPTION WHEN OTHERS THEN
        n := n + 1; INSERT INTO zz_resultat VALUES (n,'BLOQUANT','PL/pgSQL et declencheurs',SQLERRM);
    END;

    n := n + 1;
    INSERT INTO zz_resultat VALUES (n,
        CASE WHEN has_schema_privilege(current_user,'public','CREATE') THEN 'OK' ELSE 'BLOQUANT' END,
        'Droit CREATE sur public', 'le socle y cree ses tables');

    n := n + 1;
    INSERT INTO zz_resultat VALUES (n,
        CASE WHEN EXISTS (SELECT 1 FROM zz_resultat WHERE verdict='BLOQUANT')
             THEN 'ECHEC' ELSE 'VERDICT' END,
        CASE WHEN EXISTS (SELECT 1 FROM zz_resultat WHERE verdict='BLOQUANT')
             THEN 'Le schema ne s''appliquera PAS' ELSE 'Le serveur porte le schema' END,
        (SELECT count(*)::text || ' blocage(s)' FROM zz_resultat WHERE verdict='BLOQUANT'));
END $q$;

SELECT verdict, test, detail FROM zz_resultat ORDER BY rang;
