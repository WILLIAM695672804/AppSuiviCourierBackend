-- ---------------------------------------------------------------------
--  Le serveur PostgreSQL peut-il porter ce schema ?
--
--  A executer sur la base d'un hebergement candidat, AVANT d'y copier
--  quoi que ce soit. Tout se passe dans une transaction annulee : rien
--  n'est cree, rien n'est laisse derriere.
--
--      psql "postgres://utilisateur:secret@hote:5432/base" -f qualifier-postgres.sql
--
--  Ou, sans acces SSH, par un copier-coller dans phpPgAdmin.
--
--  Chaque ligne du rapport teste UNE construction du socle, avec le
--  nombre d'endroits ou elle apparait. Un seul « NON » sur les lignes
--  marquees [BLOQUANT] suffit a fermer le dossier : ces constructions
--  n'ont pas d'equivalent, et les contourner reviendrait a reecrire le
--  schema.
-- ---------------------------------------------------------------------

BEGIN;

DO $qualification$
DECLARE
    bloquants int := 0;
    extension_nom text;
BEGIN
    RAISE NOTICE '';
    RAISE NOTICE '=== Serveur ===';
    RAISE NOTICE '%', version();
    RAISE NOTICE 'Utilisateur : %   Base : %', current_user, current_database();
    RAISE NOTICE 'Superutilisateur : %', (SELECT usesuper FROM pg_user WHERE usename = current_user);
    RAISE NOTICE '';

    -- -----------------------------------------------------------------
    --  Version. Le schema declare PostgreSQL 16 minimum.
    -- -----------------------------------------------------------------
    IF current_setting('server_version_num')::int >= 160000 THEN
        RAISE NOTICE '[OK]       Version >= 16';
    ELSE
        RAISE NOTICE '[BLOQUANT] Version % — le socle exige 16', current_setting('server_version');
        bloquants := bloquants + 1;
    END IF;

    -- -----------------------------------------------------------------
    --  Les quatre extensions. Depuis PostgreSQL 13 elles sont « trusted »
    --  et le proprietaire de la base peut les creer — a condition que les
    --  binaires « contrib » soient installes sur le serveur, ce que seul
    --  ce test dit.
    -- -----------------------------------------------------------------
    FOREACH extension_nom IN ARRAY ARRAY['pgcrypto', 'btree_gist', 'pg_trgm', 'unaccent']
    LOOP
        BEGIN
            EXECUTE format('CREATE EXTENSION IF NOT EXISTS %I', extension_nom);
            RAISE NOTICE '[OK]       Extension %', extension_nom;
        EXCEPTION WHEN OTHERS THEN
            RAISE NOTICE '[BLOQUANT] Extension % — %', extension_nom, SQLERRM;
            bloquants := bloquants + 1;
        END;
    END LOOP;

    -- -----------------------------------------------------------------
    --  Partitionnement declaratif — 3 tables du socle : `evenement` et
    --  `champ_historique` par annee, `journal_acces` par mois.
    -- -----------------------------------------------------------------
    BEGIN
        CREATE TABLE zz_partition (id bigint, le date NOT NULL) PARTITION BY RANGE (le);
        CREATE TABLE zz_partition_2026 PARTITION OF zz_partition
            FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
        RAISE NOTICE '[OK]       Partitionnement declaratif (3 tables)';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[BLOQUANT] Partitionnement — %', SQLERRM;
        bloquants := bloquants + 1;
    END;

    -- -----------------------------------------------------------------
    --  Contrainte d'exclusion sur intervalle. Elle empeche deux periodes
    --  de se chevaucher, et n'a d'equivalent dans aucun autre SGBD.
    -- -----------------------------------------------------------------
    BEGIN
        CREATE TABLE zz_exclusion (
            id bigint,
            periode tstzrange,
            EXCLUDE USING gist (id WITH =, periode WITH &&)
        );
        RAISE NOTICE '[OK]       EXCLUDE USING gist';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[BLOQUANT] EXCLUDE USING gist — %', SQLERRM;
        bloquants := bloquants + 1;
    END;

    -- -----------------------------------------------------------------
    --  Recherche plein texte : colonne generee + index GIN. 18 endroits.
    -- -----------------------------------------------------------------
    BEGIN
        CREATE TABLE zz_recherche (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            objet text,
            recherche tsvector GENERATED ALWAYS AS (to_tsvector('french', coalesce(objet, ''))) STORED
        );
        CREATE INDEX ON zz_recherche USING GIN (recherche);
        PERFORM to_tsvector('french', 'accuse de reception'), unaccent('Étude');
        RAISE NOTICE '[OK]       TSVECTOR genere + index GIN + configuration « french »';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[BLOQUANT] Plein texte — %', SQLERRM;
        bloquants := bloquants + 1;
    END;

    -- -----------------------------------------------------------------
    --  Index BRIN — les journaux, ou l'ordre physique suit le temps.
    -- -----------------------------------------------------------------
    BEGIN
        CREATE TABLE zz_brin (le timestamptz);
        CREATE INDEX ON zz_brin USING BRIN (le);
        RAISE NOTICE '[OK]       Index BRIN';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[BLOQUANT] Index BRIN — %', SQLERRM;
        bloquants := bloquants + 1;
    END;

    -- -----------------------------------------------------------------
    --  14 fonctions PL/pgSQL et 11 declencheurs portent des regles que
    --  l'application ne peut pas contourner.
    -- -----------------------------------------------------------------
    BEGIN
        CREATE FUNCTION zz_declencheur() RETURNS trigger LANGUAGE plpgsql AS $f$
        BEGIN RETURN NEW; END $f$;
        CREATE TRIGGER zz BEFORE INSERT ON zz_brin FOR EACH ROW EXECUTE FUNCTION zz_declencheur();
        RAISE NOTICE '[OK]       PL/pgSQL et declencheurs (14 fonctions, 11 declencheurs)';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[BLOQUANT] PL/pgSQL — %', SQLERRM;
        bloquants := bloquants + 1;
    END;

    -- -----------------------------------------------------------------
    --  Le dictionnaire de donnees vit en base, en COMMENT ON. 40 entrees.
    -- -----------------------------------------------------------------
    BEGIN
        COMMENT ON TABLE zz_brin IS 'essai';
        RAISE NOTICE '[OK]       COMMENT ON (dictionnaire de donnees)';
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE '[AVERTIR]  COMMENT ON — %', SQLERRM;
    END;

    -- -----------------------------------------------------------------
    --  Le socle cree ses objets dans `public`. Sur un mutualise, ce droit
    --  est parfois retire.
    -- -----------------------------------------------------------------
    IF has_schema_privilege(current_user, 'public', 'CREATE') THEN
        RAISE NOTICE '[OK]       Droit CREATE sur le schema public';
    ELSE
        RAISE NOTICE '[BLOQUANT] Aucun droit CREATE sur public';
        bloquants := bloquants + 1;
    END IF;

    RAISE NOTICE '';
    RAISE NOTICE '=== Verdict ===';
    IF bloquants = 0 THEN
        RAISE NOTICE 'Le serveur porte le schema. Restent les demons et LibreOffice,';
        RAISE NOTICE 'qui ne dependent pas de la base.';
    ELSE
        RAISE NOTICE '% blocage(s). Le schema ne s''appliquera pas sur ce serveur.', bloquants;
    END IF;
    RAISE NOTICE '';
END
$qualification$;

-- Rien n'est conserve : le serveur est laisse exactement comme il a ete
-- trouve, y compris les extensions, qui sont creees puis annulees.
ROLLBACK;
